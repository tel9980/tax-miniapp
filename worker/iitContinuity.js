export function iitWithUrl(list) {
  // 显式给 null 的条目（法规库确实未收录）保持无链接，绝不拿法规库首页冒充原文
  return list.map((x) => ({ ...x, url: x.url === undefined ? IIT_LAW.url : x.url }));
}
